func (a *App) T(key string, args ...any) string {
	lang := a.cfg.Lang
	if dict[lang] == nil {
		lang = "en"
	}
	s, ok := dict[lang][key]
	if !ok {
		s = dict["en"][key]
	}
	if len(args) > 0 {
		return fmt.Sprintf(s, args...)
	}
	return s
}

func fmtTokens(n int64) string {
	switch {
	case n >= 1_000_000:
		return strings.TrimSuffix(fmt.Sprintf("%.1f", float64(n)/1e6), ".0") + "M"
	case n >= 1000:
		return fmt.Sprintf("%dk", n/1000)
	}
	return fmt.Sprint(n)
}
